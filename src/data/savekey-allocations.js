// The names of whoever has pages of the save files from first to last (a save file is the high byte of the address): [] when all of them are free.
export const saveFileOwners = (first, last) => {
  const owners = [];
  SAVEKEY_ALLOCATIONS.forEach(([startPage, endPage, title]) => {
    if (startPage <= last * 4 + 3 && endPage >= first * 4 && !owners.includes(title)) owners.push(title);
  });
  return owners;
};
